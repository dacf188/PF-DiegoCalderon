    private void BotonConsultarCarnetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonConsultarCarnetActionPerformed
        // TODO add your handling code here:
        try {
            String carnet = JOptionPane.showInputDialog(this, "Ingrese el número de carnet a consultar:");
            if (carnet != null && !carnet.trim().isEmpty()) {
                Estudiante est = controlador.obtenerEstudiantePorCarnet(carnet.trim());
                if (est != null) {
                    modeloTabla.setRowCount(0);
                    modeloTabla.addRow(new Object[]{
                        est.getNoCarnetEstudiante(),
                        est.getNombreEstudiante(),
                        est.getApellidoEstudiante(),
                        est.getEdadEstudiante(),
                        est.getFechaNacimientoEstudiante(),
                        est.getGeneroEstudiante(),
                        est.getCorreoElectronicoEstudiante(),
                        est.getTelefonoEstudiante(),
                        est.getNoDpiEstudiante()
                    });

                    jTextField1.setText(est.getNoCarnetEstudiante());
                    jTextField2.setText(est.getNombreEstudiante());
                    jTextField3.setText(est.getApellidoEstudiante());
                    jTextField4.setText(String.valueOf(est.getEdadEstudiante()));
                    jTextField5.setText(est.getFechaNacimientoEstudiante() != null ? est.getFechaNacimientoEstudiante().toString() : "");
                    jComboBox1.setSelectedItem(est.getGeneroEstudiante());
                    jTextField6.setText(est.getCorreoElectronicoEstudiante());
                    jTextField7.setText(est.getTelefonoEstudiante());
                    jTextField8.setText(est.getNoDpiEstudiante());
                } else {
                    JOptionPane.showMessageDialog(this, "Estudiante no encontrado.");
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al consultar: " + e.getMessage());
        }
    }//GEN-LAST:event_BotonConsultarCarnetActionPerformed

