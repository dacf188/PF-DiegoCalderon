    private void BotonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonGuardarActionPerformed
        // TODO add your handling code here:
        try {
            String carnet = jTextField1.getText().trim();
            String nombre = jTextField2.getText().trim();
            String apellido = jTextField3.getText().trim();
            int edad = Integer.parseInt(jTextField4.getText().trim());
            LocalDate fechaNacimiento = LocalDate.parse(jTextField5.getText().trim()); 
            String genero = jComboBox1.getSelectedItem().toString();
            String correo = jTextField6.getText().trim();
            String telefono = jTextField7.getText().trim();
            String dpi = jTextField8.getText().trim();

            boolean agregado = controlador.agregarEstudiante(
                carnet, nombre, apellido, edad, fechaNacimiento, genero, correo, telefono, dpi
            );

            if (agregado) {
                JOptionPane.showMessageDialog(this, "Estudiante guardado correctamente.");
                
                // Mostrar únicamente el nuevo estudiante ingresado en la tabla
                modeloTabla.setRowCount(0);
                modeloTabla.addRow(new Object[]{
                    carnet, nombre, apellido, edad, fechaNacimiento, genero, correo, telefono, dpi
                });

                limpiarCamposFormulario();
            } else {
                JOptionPane.showMessageDialog(this, "Error al guardar el estudiante.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Verifica los datos ingresados: " + e.getMessage());
        }
    }//GEN-LAST:event_BotonGuardarActionPerformed

    private void BotonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonActualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (!enModoEdicion) {
                // --- PASO 1: Pedir el carnet, buscarlo y cargarlo en los campos y tabla ---
                String carnetBuscado = JOptionPane.showInputDialog(this, "Ingrese el número de carnet del estudiante a actualizar:");
                if (carnetBuscado != null && !carnetBuscado.trim().isEmpty()) {
                    Estudiante est = controlador.obtenerEstudiantePorCarnet(carnetBuscado.trim());

                    if (est != null) {
                        enModoEdicion = true; // Activamos el estado de edición
                        
                        // Cargar datos actuales en las cajas de texto
                        jTextField1.setText(est.getNoCarnetEstudiante());
                        jTextField1.setEnabled(false); // Bloqueamos el carnet para no alterar la llave primaria
                        jTextField2.setText(est.getNombreEstudiante());
                        jTextField3.setText(est.getApellidoEstudiante());
                        jTextField4.setText(String.valueOf(est.getEdadEstudiante()));
                        jTextField5.setText(est.getFechaNacimientoEstudiante() != null ? est.getFechaNacimientoEstudiante().toString() : "");
                        jComboBox1.setSelectedItem(est.getGeneroEstudiante());
                        jTextField6.setText(est.getCorreoElectronicoEstudiante());
                        jTextField7.setText(est.getTelefonoEstudiante());
                        jTextField8.setText(est.getNoDpiEstudiante());

                        // Mostrar únicamente este registro en la tabla
                        modeloTabla.setRowCount(0);
                        modeloTabla.addRow(new Object[]{
                            est.getNoCarnetEstudiante(),
                            est.getNombreEstudiante(),
                            est.getApellidoEstudiante(),
                            est.getEdadEstudiante(),
                            est.getFechaNacimientoEstudiante(),
                            est.getGeneroEstudiante(),
                            est.getCorreoElectronicoEstudiante(),
                            est.getTelefonoEstudiante(),
                            est.getNoDpiEstudiante()
                        });

                        JOptionPane.showMessageDialog(this, "Datos cargados. Modifique lo necesario y presione 'Actualizar' nuevamente.");
                    } else {
                        JOptionPane.showMessageDialog(this, "No se encontró ningún estudiante con el carnet: " + carnetBuscado);
                    }
                }
            } else {
                // --- PASO 2: Guardar las modificaciones hechas en las cajas de texto ---
                String carnet = jTextField1.getText().trim();
                Estudiante estActual = controlador.obtenerEstudiantePorCarnet(carnet);

                if (estActual != null) {
                    boolean actualizado = controlador.actualizarEstudiante(
                        estActual.getIdEstudiante(),
                        carnet,
                        jTextField2.getText().trim(),
                        jTextField3.getText().trim(),
                        Integer.parseInt(jTextField4.getText().trim()),
                        LocalDate.parse(jTextField5.getText().trim()),
                        jComboBox1.getSelectedItem().toString(),
                        jTextField6.getText().trim(),
                        jTextField7.getText().trim(),
                        jTextField8.getText().trim()
                    );

                    if (actualizado) {
                        JOptionPane.showMessageDialog(this, "Estudiante actualizado correctamente.");
                        
                        // Mostrar únicamente el registro ya modificado en la tabla
                        modeloTabla.setRowCount(0);
                        modeloTabla.addRow(new Object[]{
                            carnet,
                            jTextField2.getText().trim(),
                            jTextField3.getText().trim(),
                            Integer.parseInt(jTextField4.getText().trim()),
                            LocalDate.parse(jTextField5.getText().trim()),
                            jComboBox1.getSelectedItem().toString(),
                            jTextField6.getText().trim(),
                            jTextField7.getText().trim(),
                            jTextField8.getText().trim()
                        });

                        limpiarCamposFormulario();
                    } else {
                        JOptionPane.showMessageDialog(this, "No se pudo actualizar el registro.");
                    }
                }
                
                enModoEdicion = false; // Reiniciamos el estado
                jTextField1.setEnabled(true); // Reactivamos el campo carnet
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error en el proceso de actualización: " + e.getMessage());
            enModoEdicion = false;
            jTextField1.setEnabled(true);
        }
                   
    }//GEN-LAST:event_BotonActualizarActionPerformed

    private void BotonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonEliminarActionPerformed
        // TODO add your handling code here:
        try {
            String carnet = JOptionPane.showInputDialog(this, "Ingrese el número de carnet a eliminar:");
            if (carnet != null && !carnet.trim().isEmpty()) {
                boolean eliminado = controlador.eliminarEstudiantePorCarnet(carnet.trim());
                if (eliminado) {
                    JOptionPane.showMessageDialog(this, "Estudiante eliminado.");
                    cargarEstudiantes();
                } else {
                    JOptionPane.showMessageDialog(this, "No se encontró el carnet.");
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
    }//GEN-LAST:event_BotonEliminarActionPerformed

    private void limpiarCamposFormulario() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
        jComboBox1.setSelectedIndex(0);
        jTextField6.setText("");
        jTextField7.setText("");
        jTextField8.setText("");
    }
    
    public void cargarEstudiantes() {
        modeloTabla.setRowCount(0);
        for (Estudiante est : controlador.obtenerEstudiantes()) {
            modeloTabla.addRow(new Object[]{
                est.getNoCarnetEstudiante(),
                est.getNombreEstudiante(),
                est.getApellidoEstudiante(),
                est.getEdadEstudiante(),
                est.getFechaNacimientoEstudiante(),
                est.getGeneroEstudiante(),
                est.getCorreoElectronicoEstudiante(),
                est.getTelefonoEstudiante(),
                est.getNoDpiEstudiante()
            });
        }
    }

