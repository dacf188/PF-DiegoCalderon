    public void cargarAsignaciones (){
        //LIMPIA TODAS LAS FILAS ACTUALES PARA EVITAR DUPLICADOS
        modeloTabla.setRowCount(0);
        //PASA OBJETOS DATE A TEXTO LEGIBLE
        SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");
        //RECORRE LA VISTA DESDE EL CONTROLADOR
        for (Asignacion asig : controlador.obtenerTodos()){
            modeloTabla.addRow(new Object[]{
                asig.getNoCarnet(),
                asig.getIdCurso(),
                asig.getCalificacion(),
                //VALIDA QUE LA FECHA NO SEA NULA ANTES DE FORMATEARLA
                asig.getFechaAprobacion() != null ? sdf.format(asig.getFechaAprobacion()): ""
            });
        }
    }
